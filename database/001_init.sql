CREATE OR REPLACE FUNCTION lifegen_notify_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE revision bigint;
BEGIN
 INSERT INTO app_events(entity,operation) VALUES(TG_TABLE_NAME,TG_OP) RETURNING id INTO revision;
 PERFORM pg_notify('lifegen_changes',json_build_object('revision',revision,'entity',TG_TABLE_NAME,'operation',TG_OP)::text);
 RETURN NULL;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['people','services','records','networks','lifegroups','memberships','settings','monthly_prizes','vip_registrations','vip_checkins','community_posts','prayer_reactions'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS lifegen_changed ON %I',t);
  EXECUTE format('CREATE TRIGGER lifegen_changed AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION lifegen_notify_change()',t);
 END LOOP;
END $$;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC;
INSERT INTO schema_migrations(version) VALUES('001_init') ON CONFLICT DO NOTHING;
COMMIT;
