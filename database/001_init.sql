CREATE TABLE IF NOT EXISTS staff_users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text NOT NULL UNIQUE, display_name text NOT NULL,
 password_hash text NOT NULL, role_id text NOT NULL CHECK(role_id IN ('admin','staff','viewer')),
 is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(),
 last_login_at timestamptz, failed_attempts integer NOT NULL DEFAULT 0, locked_until timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS staff_username_ci ON staff_users(lower(username));
CREATE TABLE IF NOT EXISTS staff_sessions (
 token_hash text PRIMARY KEY, user_id bigint NOT NULL REFERENCES staff_users(id) ON DELETE CASCADE,
 csrf_token text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL, last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS staff_sessions_expiry ON staff_sessions(expires_at);
CREATE TABLE IF NOT EXISTS people (
 id bigint PRIMARY KEY, person_code text NOT NULL UNIQUE,
 first_name text NOT NULL CHECK(length(first_name) BETWEEN 1 AND 200), last_name text NOT NULL DEFAULT '',
 full_name text, middle_name text, photo text, birthdate date, age integer CHECK(age BETWEEN 1 AND 120),
 sex text CHECK(sex IN ('male','female')), contact_number text, email text, address text, school text,
 course_year text, occupation text, ministry text, inviter text,
 status text NOT NULL DEFAULT 'first_timer' CHECK(status IN ('first_timer','new_believer','regular','member','leader','volunteer','inactive')),
 date_registered date NOT NULL, date_first_attended date, notes text,
 preferred_area text, preferred_day text CHECK(preferred_day IN ('mon','tue','wed','thu','fri','sat','sun')),
 preferred_time text CHECK(preferred_time IN ('morning','afternoon','evening')), preferred_category text,
 privacy_consent_at date, registration_source text NOT NULL DEFAULT 'staff',
 is_demo boolean NOT NULL DEFAULT false, archived_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), extras jsonb NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS people_name_search ON people(lower(last_name),lower(first_name));
CREATE INDEX IF NOT EXISTS people_contact_search ON people(regexp_replace(coalesce(contact_number,''),'[^0-9]','','g'));
CREATE INDEX IF NOT EXISTS people_status_idx ON people(status) WHERE archived_at IS NULL;
CREATE TABLE IF NOT EXISTS services (
 id bigint PRIMARY KEY, service_date date NOT NULL UNIQUE CHECK(EXTRACT(DOW FROM service_date)=0),
 service_type text NOT NULL DEFAULT 'lifegen', notes text, is_demo boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), extras jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS networks (
 id bigint PRIMARY KEY, name text NOT NULL, gender text CHECK(gender IN ('boys','girls')),
 leader_person_id bigint REFERENCES people(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
 leader_name text, parent_network_id bigint REFERENCES networks(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
 notes text, is_active boolean NOT NULL DEFAULT true, is_demo boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), extras jsonb NOT NULL DEFAULT '{}',
 CHECK(parent_network_id IS NULL OR parent_network_id<>id)
);
CREATE TABLE IF NOT EXISTS lifegroups (
 id bigint PRIMARY KEY, name text NOT NULL, gender text CHECK(gender IN ('boys','girls')),
 leader_person_id bigint REFERENCES people(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED, leader_name text,
 network text, network_id bigint REFERENCES networks(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
 area text, schedule_day text CHECK(schedule_day IN ('mon','tue','wed','thu','fri','sat','sun')),
 schedule_time text CHECK(schedule_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'), category text,
 capacity integer CHECK(capacity BETWEEN 1 AND 999), venue text, notes text,
 is_active boolean NOT NULL DEFAULT true, is_demo boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), extras jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS memberships (
 id bigint PRIMARY KEY, lifegroup_id bigint NOT NULL REFERENCES lifegroups(id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
 person_id bigint NOT NULL REFERENCES people(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
 joined_at date NOT NULL, left_at date, role text NOT NULL DEFAULT 'member' CHECK(role IN ('member','leader','assistant')),
 notes text, extras jsonb NOT NULL DEFAULT '{}', CHECK(left_at IS NULL OR left_at>=joined_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_group_per_person ON memberships(person_id) WHERE left_at IS NULL;
CREATE INDEX IF NOT EXISTS memberships_group_idx ON memberships(lifegroup_id);
CREATE TABLE IF NOT EXISTS records (
 id bigint PRIMARY KEY, service_id bigint NOT NULL REFERENCES services(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
 person_id bigint NOT NULL REFERENCES people(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
 status text NOT NULL CHECK(status IN ('present','absent')), classification text CHECK(classification IN ('first_timer','returning')),
 recorded_by bigint REFERENCES staff_users(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED, recorded_by_name text,
 recorded_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), source text NOT NULL DEFAULT 'staff',
