-- LIFEGEN classification and role-history foundation.
-- Review and test on an isolated development database before applying to production.
-- Do not conflate church classification with people.status or staff_users.role_id.
BEGIN;
ALTER TABLE public.people
  ADD COLUMN IF NOT EXISTS discipleship_classification text;
ALTER TABLE public.people
  DROP CONSTRAINT IF EXISTS people_discipleship_classification_check;
ALTER TABLE public.people
  ADD CONSTRAINT people_discipleship_classification_check
  CHECK (discipleship_classification IS NULL OR discipleship_classification IN ('network_leader','cell_leader','member','vip'));
CREATE TABLE IF NOT EXISTS public.people_classification_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE RESTRICT,
  previous_classification text,
  new_classification text NOT NULL
    CHECK (new_classification IN ('network_leader','cell_leader','member','vip')),
  changed_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  changed_at timestamptz NOT NULL DEFAULT now(),
  reason text,
  CHECK (previous_classification IS NULL OR previous_classification IN ('network_leader','cell_leader','member','vip'))
);
CREATE INDEX IF NOT EXISTS idx_people_classification_history_person_time
  ON public.people_classification_history (person_id, changed_at DESC);
CREATE INDEX IF NOT EXISTS idx_people_discipleship_classification
  ON public.people (discipleship_classification);
ALTER TABLE public.people_classification_history ENABLE ROW LEVEL SECURITY;
-- Intentionally no Data API policies: backend server uses existing trusted database
-- connection and must authorize role changes before writing audit history.
COMMIT;
