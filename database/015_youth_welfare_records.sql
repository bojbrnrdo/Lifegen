-- Additive Youth Welfare response storage and review workflow.
-- Answers stay linked to the canonical LIFEGEN People row; no People or Tracker
-- rows are copied or overwritten. All data access remains server-mediated.
BEGIN;
SELECT pg_advisory_xact_lock(72114026);

CREATE TABLE IF NOT EXISTS public.youth_welfare_records (
  person_id bigint PRIMARY KEY REFERENCES public.people(id) ON DELETE CASCADE,
  messenger_facebook_name text CHECK (messenger_facebook_name IS NULL OR length(messenger_facebook_name) <= 200),
  complete_address text CHECK (complete_address IS NULL OR length(complete_address) <= 500),
  contact_number text CHECK (contact_number IS NULL OR length(contact_number) <= 40),
  parent_guardian_name text CHECK (parent_guardian_name IS NULL OR length(parent_guardian_name) <= 200),
  parent_guardian_contact text CHECK (parent_guardian_contact IS NULL OR length(parent_guardian_contact) <= 40),
  cell_leader_person_id bigint REFERENCES public.people(id) ON DELETE SET NULL,
  cell_leader_manual_name text CHECK (cell_leader_manual_name IS NULL OR length(cell_leader_manual_name) <= 200),
  education_status text CHECK (education_status IS NULL OR education_status IN ('currently_studying','out_of_school','currently_als','working_student','graduated')),
  grade_year_level text CHECK (grade_year_level IS NULL OR grade_year_level IN (
    'elementary_grade_6','junior_high_grade_7','junior_high_grade_8','junior_high_grade_9','junior_high_grade_10',
    'senior_high_grade_11','senior_high_grade_12','college_first_year','college_second_year','college_third_year','college_fourth_year',
    'als_junior_high','als_senior_high','tesda_vocational'
  )),
  school_stop_period text CHECK (school_stop_period IS NULL OR school_stop_period IN (
    'current_ay_2026_2027','last_school_year','two_years_ago','three_or_more_years_ago','unsure'
  )),
  school_stop_reasons text[] NOT NULL DEFAULT ARRAY[]::text[],
  continue_studies text CHECK (continue_studies IS NULL OR continue_studies IN (
    'yes_definitely','yes_need_help','maybe','not_right_now','no'
  )),
  church_invited_at date,
  lcsol_enrolled boolean,
  lcsol_status text CHECK (lcsol_status IS NULL OR lcsol_status IN (
    'not_yet_started','currently_in_consolidation','done_in_consolidation','done_in_pre_encounter',
    'done_encounter','done_post_encounter','currently_in_undercover','done_in_undercover',
    'sol_1','sol_2','sol_3','graduate_completed'
  )),
  welfare_consent_at timestamptz,
  welfare_consent_version text,
  verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending','verified')),
  verified_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  verified_at timestamptz,
  source text NOT NULL DEFAULT 'public_registration' CHECK (source IN ('public_registration','staff_entry','approved_update')),
  created_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((verification_status='verified' AND verified_at IS NOT NULL) OR (verification_status='pending' AND verified_at IS NULL)),
  CHECK (lcsol_enrolled IS NULL OR lcsol_status IS NULL OR
    (lcsol_enrolled AND lcsol_status<>'not_yet_started') OR
    (NOT lcsol_enrolled AND lcsol_status='not_yet_started')),
  CHECK (school_stop_reasons <@ ARRAY[
    'financial_problem','needed_to_work','family_problem','personal_reason','academic_struggle',
    'health_problem','missing_school_requirements','prefer_not_to_say'
  ]::text[])
);
CREATE INDEX IF NOT EXISTS youth_welfare_records_education_idx
  ON public.youth_welfare_records(education_status,grade_year_level);
CREATE INDEX IF NOT EXISTS youth_welfare_records_lcsol_idx
  ON public.youth_welfare_records(lcsol_enrolled,lcsol_status);
CREATE INDEX IF NOT EXISTS youth_welfare_records_verification_idx
  ON public.youth_welfare_records(verification_status,updated_at DESC);

-- A re-submission for an existing person is kept as a pending proposal rather
-- than silently replacing their current Youth Welfare answers. An authorized
-- administrator reviews and applies it through the API.
CREATE TABLE IF NOT EXISTS public.youth_welfare_record_updates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  proposed_answers jsonb NOT NULL CHECK (jsonb_typeof(proposed_answers)='object'),
  welfare_consent_at timestamptz NOT NULL,
  source text NOT NULL DEFAULT 'public_registration' CHECK (source IN ('public_registration','staff_entry')),
  request_hash text UNIQUE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  reviewed_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((status='pending' AND reviewed_at IS NULL) OR (status<>'pending' AND reviewed_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS youth_welfare_record_updates_pending_idx
  ON public.youth_welfare_record_updates(status,created_at DESC);
CREATE INDEX IF NOT EXISTS youth_welfare_record_updates_person_idx
  ON public.youth_welfare_record_updates(person_id,created_at DESC);

-- Preserve prior authorized answers when an administrator applies a reviewed
-- correction. Snapshots are private and available only through Admin endpoints.
CREATE TABLE IF NOT EXISTS public.youth_welfare_record_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  actor_id bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action IN ('record_updated','public_update_approved')),
  record_snapshot jsonb NOT NULL CHECK (jsonb_typeof(record_snapshot)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS youth_welfare_record_history_person_idx
  ON public.youth_welfare_record_history(person_id,created_at DESC);

-- Server-side idempotency prevents a retry after a lost response from adding a
-- second review proposal or membership event. Only a hash of the browser key is
-- retained; the response is scoped to that same random request key.
CREATE TABLE IF NOT EXISTS public.public_registration_requests (
  request_hash text PRIMARY KEY,
  person_id bigint REFERENCES public.people(id) ON DELETE CASCADE,
  response jsonb NOT NULL CHECK (jsonb_typeof(response)='object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS public_registration_requests_person_idx
  ON public.public_registration_requests(person_id,created_at DESC);

-- Add a portal-only Youth Welfare Staff role to the existing login system.
-- Existing account values are preserved; no primary LIFEGEN role is rewritten.
ALTER TABLE public.staff_users
  DROP CONSTRAINT IF EXISTS staff_users_role_id_check;
ALTER TABLE public.staff_users
  ADD CONSTRAINT staff_users_role_id_check
  CHECK (role_id IN ('admin','staff','viewer','youth_welfare_admin','youth_welfare_staff','youth_welfare_viewer'));

-- The additive access table also supports the limited staff assignment.
ALTER TABLE public.youth_welfare_access
  DROP CONSTRAINT IF EXISTS youth_welfare_access_role_id_check;
ALTER TABLE public.youth_welfare_access
  ADD CONSTRAINT youth_welfare_access_role_id_check
  CHECK (role_id IN ('youth_welfare_admin','youth_welfare_staff','youth_welfare_viewer'));

DO $$
DECLARE table_name text; role_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['youth_welfare_records','youth_welfare_record_updates','youth_welfare_record_history','public_registration_requests'] LOOP
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',table_name);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',table_name,role_name);
      END IF;
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('DROP TRIGGER IF EXISTS lifegen_changed ON public.%I',table_name);
    EXECUTE format('CREATE TRIGGER lifegen_changed AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.lifegen_notify_change()',table_name);
  END LOOP;
END $$;

REVOKE ALL ON TABLE public.youth_welfare_access FROM PUBLIC;
DO $$
DECLARE role_name text;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.youth_welfare_access FROM %I',role_name);
    END IF;
  END LOOP;
END $$;
ALTER TABLE public.youth_welfare_access ENABLE ROW LEVEL SECURITY;

INSERT INTO public.schema_migrations(version)
VALUES ('015_youth_welfare_records')
ON CONFLICT DO NOTHING;
COMMIT;
