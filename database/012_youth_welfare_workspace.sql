-- Persistent Youth Welfare workspace tools: follow-up tasks, saved views,
-- report templates, and per-user reminder dismissals. Additive; no People,
-- registration, attendance, or VIP rows are changed.
BEGIN;
SELECT pg_advisory_xact_lock(72114026);

CREATE TABLE IF NOT EXISTS public.youth_welfare_follow_up_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  task_type text NOT NULL CHECK (task_type IN ('data_verification','registration_review','admin_follow_up')),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 160),
  notes text CHECK (notes IS NULL OR length(notes) <= 500),
  status text NOT NULL DEFAULT 'needs_review' CHECK (status IN ('needs_review','in_progress','resolved')),
  assigned_to bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  due_date date,
  created_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  resolved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((status = 'resolved') = (resolved_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS youth_welfare_tasks_person_status_idx
  ON public.youth_welfare_follow_up_tasks(person_id,status,due_date);
CREATE INDEX IF NOT EXISTS youth_welfare_tasks_due_idx
  ON public.youth_welfare_follow_up_tasks(due_date,status) WHERE due_date IS NOT NULL;
-- Repeated submissions cannot create duplicate active tasks for the same person,
-- task type, and title. Resolved tasks may be recreated after a new review.
CREATE UNIQUE INDEX IF NOT EXISTS youth_welfare_tasks_open_dedupe_idx
  ON public.youth_welfare_follow_up_tasks(person_id,task_type,lower(btrim(title)))
  WHERE status IN ('needs_review','in_progress');

CREATE TABLE IF NOT EXISTS public.youth_welfare_saved_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.staff_users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  filters jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(filters) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS youth_welfare_saved_views_user_name_idx
  ON public.youth_welfare_saved_views(user_id,lower(btrim(name)));

CREATE TABLE IF NOT EXISTS public.youth_welfare_report_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.staff_users(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  config jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(config) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS youth_welfare_report_templates_user_name_idx
  ON public.youth_welfare_report_templates(user_id,lower(btrim(name)));

CREATE TABLE IF NOT EXISTS public.youth_welfare_reminder_dismissals (
  user_id bigint NOT NULL REFERENCES public.staff_users(id) ON DELETE CASCADE,
  task_id bigint NOT NULL REFERENCES public.youth_welfare_follow_up_tasks(id) ON DELETE CASCADE,
  due_date date NOT NULL,
  dismissed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(user_id,task_id,due_date)
);

DO $$
DECLARE table_name text; role_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'youth_welfare_follow_up_tasks',
    'youth_welfare_saved_views',
    'youth_welfare_report_templates',
    'youth_welfare_reminder_dismissals'
  ] LOOP
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',table_name);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',table_name,role_name);
      END IF;
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('DROP TRIGGER IF EXISTS lifegen_changed ON public.%I',table_name);
    EXECUTE format('CREATE TRIGGER lifegen_changed AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.lifegen_notify_change()',table_name);
  END LOOP;
END $$;

INSERT INTO public.schema_migrations(version)
VALUES ('012_youth_welfare_workspace')
ON CONFLICT DO NOTHING;
COMMIT;
