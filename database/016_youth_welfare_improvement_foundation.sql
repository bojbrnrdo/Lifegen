-- Youth Welfare improvement foundation: admin-controlled eligibility policy,
-- minimal Care Status, task outcomes/priorities, and append-only status events.
-- Additive only. This migration is source and is NOT run against production here.
BEGIN;
SELECT pg_advisory_xact_lock(72114026);

-- A null lower/upper bound preserves the existing eligibility scope. Admins may
-- configure one or both age limits later; no age policy is silently assumed.
CREATE TABLE IF NOT EXISTS public.youth_welfare_eligibility_policy (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  minimum_age smallint CHECK (minimum_age IS NULL OR minimum_age BETWEEN 0 AND 120),
  maximum_age smallint CHECK (maximum_age IS NULL OR maximum_age BETWEEN 0 AND 120),
  updated_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (minimum_age IS NULL OR maximum_age IS NULL OR minimum_age <= maximum_age)
);
INSERT INTO public.youth_welfare_eligibility_policy(id,minimum_age,maximum_age)
VALUES (1,NULL,NULL)
ON CONFLICT (id) DO NOTHING;

-- Care Status is a small, human-set signal. It intentionally has no narrative
-- or counselling notes attached to it.
ALTER TABLE public.youth_welfare_records
  ADD COLUMN IF NOT EXISTS care_status text,
  ADD COLUMN IF NOT EXISTS care_status_reviewed_at timestamptz;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='public.youth_welfare_records'::regclass
      AND conname='youth_welfare_records_care_status_check'
  ) THEN
    ALTER TABLE public.youth_welfare_records
      ADD CONSTRAINT youth_welfare_records_care_status_check
      CHECK (care_status IS NULL OR care_status IN ('doing_well','monitor','needs_support','urgent'));
  END IF;
END $$;

-- Task priority and closure outcomes support simple workload and effectiveness
-- reporting. Existing resolved tasks remain valid with a null outcome; new task
-- closures are required by the application to provide one.
ALTER TABLE public.youth_welfare_follow_up_tasks
  ADD COLUMN IF NOT EXISTS priority text NOT NULL DEFAULT 'normal',
  ADD COLUMN IF NOT EXISTS outcome text,
  ADD COLUMN IF NOT EXISTS closure_note text,
  ADD COLUMN IF NOT EXISTS closed_by bigint REFERENCES public.staff_users(id) ON DELETE SET NULL;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='public.youth_welfare_follow_up_tasks'::regclass
      AND conname='youth_welfare_tasks_priority_check'
  ) THEN
    ALTER TABLE public.youth_welfare_follow_up_tasks
      ADD CONSTRAINT youth_welfare_tasks_priority_check
      CHECK (priority IN ('low','normal','high','urgent'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='public.youth_welfare_follow_up_tasks'::regclass
      AND conname='youth_welfare_tasks_outcome_check'
  ) THEN
    ALTER TABLE public.youth_welfare_follow_up_tasks
      ADD CONSTRAINT youth_welfare_tasks_outcome_check
      CHECK (outcome IS NULL OR outcome IN (
        'reached_no_need','reached_support_arranged','unreachable','referred','declined'
      ));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid='public.youth_welfare_follow_up_tasks'::regclass
      AND conname='youth_welfare_tasks_closure_note_check'
  ) THEN
    ALTER TABLE public.youth_welfare_follow_up_tasks
      ADD CONSTRAINT youth_welfare_tasks_closure_note_check
      CHECK (closure_note IS NULL OR length(closure_note) <= 500);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS youth_welfare_tasks_assignment_status_idx
  ON public.youth_welfare_follow_up_tasks(assigned_to,status,priority,due_date);

-- Append-only, value-level snapshots for ministry-owned status fields. This is
-- separate from LIFEGEN People and Tracker history.
CREATE TABLE IF NOT EXISTS public.youth_welfare_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_id bigint NOT NULL REFERENCES public.people(id) ON DELETE CASCADE,
  field_name text NOT NULL CHECK (field_name IN (
    'category','education_status','lcsol_enrolled','lcsol_status','care_status','verification_status'
  )),
  old_value text,
  new_value text,
  actor_id bigint REFERENCES public.staff_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (old_value IS DISTINCT FROM new_value)
);
CREATE INDEX IF NOT EXISTS youth_welfare_status_history_person_idx
  ON public.youth_welfare_status_history(person_id,created_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS youth_welfare_status_history_field_idx
  ON public.youth_welfare_status_history(field_name,created_at DESC);

DO $$
DECLARE table_name text; role_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'youth_welfare_eligibility_policy',
    'youth_welfare_status_history'
  ] LOOP
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',table_name);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',table_name,role_name);
      END IF;
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('DROP TRIGGER IF EXISTS lifegen_changed ON public.%I',table_name);
    EXECUTE format('CREATE TRIGGER lifegen_changed AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.lifegen_notify_change()',table_name);
  END LOOP;
END $$;

INSERT INTO public.schema_migrations(version)
VALUES ('016_youth_welfare_improvement_foundation')
ON CONFLICT DO NOTHING;
COMMIT;
